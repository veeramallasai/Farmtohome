  static String? productImage(String key) {
    return allProductImages[_normalize(key)];
  }

  static String? categoryImage(String category) {
    return categoryImages[_normalize(category)];
  }

  static String _normalize(String value) {
    return value
        .trim()
        .toLowerCase()
        .replaceAll('&', 'and')
        .replaceAll(RegExp(r'[^a-z0-9]+'), '_')
        .replaceAll(RegExp(r'^_+|_+$'), '');
  }
